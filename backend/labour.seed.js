const SECTION = c => (c.startsWith('ME-') ? 'Mechanical Repairs' : 'Body & Paints');
const keyOf = (code, model) => `${code}|${model}`.toLowerCase();

// The price-book lines that are not yet in the labour list (matched by code + model group, whether the line is active or not),
// so a line the manager has edited or switched off is never changed or brought back.
export function missingPriceBook(existing) {
  const have = new Set((existing || []).map(r => keyOf(r.code || '', r.model_grp || '')));
  return PRICE_BOOK.filter(([code, , model]) => !have.has(keyOf(code, model))).map(([code, name, model, hours]) => ({ code, name, model_grp: model, section: SECTION(code), hours }));
}
